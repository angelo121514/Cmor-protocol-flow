SELECT set_config('request.jwt.claims',jsonb_build_object('sub',(SELECT id FROM auth.users WHERE email='admin@fixture.example.test'),'role','authenticated','aal','aal2')::text,true);
SET LOCAL ROLE authenticated;
SELECT is(public.is_admin(),true,'real PostgreSQL AAL2 administrator accepted');
