SELECT ok(NOT has_function_privilege('anon','public.start_table_session(uuid)','EXECUTE'),'UUID alone has no execution grant');
SELECT ok(NOT has_function_privilege('authenticated','public.execute_dsar(uuid,text)','EXECUTE'),'DSAR executor private');
SELECT ok(NOT has_function_privilege('authenticated','public.confirm_checkout(text,text,text,numeric,text,text)','EXECUTE'),'payment settlement private');
SELECT ok(NOT has_table_privilege('anon','public.audit_log','INSERT'),'no forged audit');
SELECT ok(NOT has_table_privilege('authenticated','public.consents','INSERT'),'no forged consent');
SELECT ok(NOT has_column_privilege('authenticated','public.profiles','role','UPDATE'),'no role escalation');
SELECT ok(NOT has_column_privilege('authenticated','public.orders','total','UPDATE'),'no client monetary override');
SELECT ok(has_table_privilege('service_role','public.restaurants','INSERT'),'explicit backend write grant exists on clean installation');
