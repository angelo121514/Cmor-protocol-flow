SELECT set_config('request.jwt.claims',jsonb_build_object('sub',(SELECT id FROM auth.users WHERE email='admin@fixture.example.test'),'role','authenticated','aal','aal1')::text,true);
SET LOCAL ROLE authenticated;
SELECT is(public.is_admin(),false,'real PostgreSQL AAL1 administrator denied');
