SELECT ok(public.is_service_actor(),'automation is separate from human administration');
SELECT is(public.is_admin(),false,'service role does not impersonate human admin');
SELECT is((SELECT enabled FROM public.accounting_cron_secret WHERE id=1),false,'external accounting cron disabled by default');
SELECT * FROM finish();
